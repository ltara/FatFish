#!/usr/bin/env bash
# Download Windows vendor assets into vendor/ and write MANIFEST.txt
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/vendor"
NAPCAT_DIR="$VENDOR/napcat"
NODE_DIR="$VENDOR/node"
MANIFEST="$VENDOR/MANIFEST.txt"

NAPCAT_VERSION="${NAPCAT_VERSION:-v4.18.41}"
NAPCAT_ASSET="NapCat.Shell.zip"
NAPCAT_URL="https://github.com/NapNeko/NapCatQQ/releases/download/${NAPCAT_VERSION}/${NAPCAT_ASSET}"

NODE_VERSION="${NODE_VERSION:-v20.20.2}"
NODE_ASSET="node-${NODE_VERSION}-win-x64.zip"
NODE_URL="https://nodejs.org/dist/${NODE_VERSION}/${NODE_ASSET}"

# DSH runtime: pinned forever (no updates after delivery). The PyPI win wheel carries a
# single-file exe with its own Node; only the exe + -rg sidecar are kept.
DSH_DIR="$VENDOR/dsh"
DSH_VERSION="0.2.1rc2"
DSH_ASSET="deepseek_harness_runtime_bin-${DSH_VERSION}-py3-none-win_amd64.whl"
DSH_URL="https://files.pythonhosted.org/packages/bc/95/8164c49a5d3430add58db8aeba6546cd05c9ab7ddd2ea3e1acf174448d86/${DSH_ASSET}"
DSH_SHA_EXPECTED="d38c18f5117859feedaaa791a0eea37b8644bc187118e7e6f3afa231a5381cb7"

mkdir -p "$NAPCAT_DIR" "$NODE_DIR" "$DSH_DIR"
TS="$(date '+%Y-%m-%dT%H:%M:%S%z')"

sha256_file() {
  if command -v sha256sum >/dev/null; then sha256sum "$1" | awk '{print $1}'
  elif command -v shasum >/dev/null; then shasum -a 256 "$1" | awk '{print $1}'
  else openssl dgst -sha256 "$1" | awk '{print $NF}'; fi
}

download() {
  local url="$1" out="$2"
  echo "[fetch] $url"
  curl -fsSL --retry 3 -o "$out" "$url"
}

# --- NapCat Shell (needs user-installed QQ) ---
NAPCAT_ZIP="$VENDOR/$NAPCAT_ASSET"
if [[ ! -f "$NAPCAT_ZIP" ]]; then
  download "$NAPCAT_URL" "$NAPCAT_ZIP"
else
  echo "[fetch] reuse $NAPCAT_ZIP"
fi
NAPCAT_SHA="$(sha256_file "$NAPCAT_ZIP")"
rm -rf "${NAPCAT_DIR:?}/"*
unzip -q -o "$NAPCAT_ZIP" -d "$NAPCAT_DIR"
echo "[fetch] napcat extracted → $NAPCAT_DIR (sha256=$NAPCAT_SHA)"
# Win cmd 秒退若 .bat 为 LF；解压后强制 CRLF（Linux 打包链路必做）
node "$ROOT/scripts/ensure-crlf.js" "$NAPCAT_DIR"

# --- Portable Node Win x64 ---
NODE_ZIP="$VENDOR/$NODE_ASSET"
if [[ ! -f "$NODE_ZIP" ]]; then
  download "$NODE_URL" "$NODE_ZIP"
else
  echo "[fetch] reuse $NODE_ZIP"
fi
NODE_SHA="$(sha256_file "$NODE_ZIP")"
TMP_NODE="$(mktemp -d)"
unzip -q -o "$NODE_ZIP" -d "$TMP_NODE"
# zip contains node-vX.Y.Z-win-x64/
INNER="$(find "$TMP_NODE" -maxdepth 1 -type d -name 'node-*' | head -1)"
rm -rf "${NODE_DIR:?}/"*
cp -a "$INNER"/. "$NODE_DIR/"
rm -rf "$TMP_NODE"
echo "[fetch] node extracted → $NODE_DIR (sha256=$NODE_SHA)"

# --- DSH runtime (sha256 pinned; mismatch aborts) ---
DSH_WHL="$VENDOR/$DSH_ASSET"
if [[ ! -f "$DSH_WHL" ]]; then
  # PyPI's CDN drops long HTTP/2 streams; force 1.1 and resume
  echo "[fetch] $DSH_URL"
  curl -fsSL --http1.1 --retry 5 --retry-all-errors -C - -o "$DSH_WHL" "$DSH_URL"
else
  echo "[fetch] reuse $DSH_WHL"
fi
DSH_SHA="$(sha256_file "$DSH_WHL")"
if [[ "$DSH_SHA" != "$DSH_SHA_EXPECTED" ]]; then
  echo "[fetch] dsh sha256 mismatch: $DSH_SHA (expected $DSH_SHA_EXPECTED)" >&2
  exit 1
fi
TMP_DSH="$(mktemp -d)"
unzip -q -o "$DSH_WHL" 'deepseek_harness_runtime/runtime/*.exe' \
  'deepseek_harness_runtime_bin-*.dist-info/licenses/*' -d "$TMP_DSH"
rm -rf "${DSH_DIR:?}/"*
cp "$TMP_DSH"/deepseek_harness_runtime/runtime/*.exe "$DSH_DIR/"
cp "$TMP_DSH"/deepseek_harness_runtime_bin-*.dist-info/licenses/* "$DSH_DIR/"
rm -rf "$TMP_DSH"
echo "[fetch] dsh extracted → $DSH_DIR (sha256=$DSH_SHA)"

cat > "$MANIFEST" <<EOM
# FatFish vendor manifest — generated by scripts/fetch-vendor
# Do not commit binary blobs under vendor/napcat or vendor/node

[napcat]
version=${NAPCAT_VERSION}
asset=${NAPCAT_ASSET}
url=${NAPCAT_URL}
sha256=${NAPCAT_SHA}
downloaded_at=${TS}
extract_dir=vendor/napcat
notes=Requires user-installed official QQ. Entry: launcher-user.bat / NapCatWinBootMain.exe

[node]
version=${NODE_VERSION}
asset=${NODE_ASSET}
url=${NODE_URL}
sha256=${NODE_SHA}
downloaded_at=${TS}
extract_dir=vendor/node
notes=Portable Node for running bridge + local-server on Windows

[dsh]
version=${DSH_VERSION}
asset=${DSH_ASSET}
url=${DSH_URL}
sha256=${DSH_SHA}
downloaded_at=${TS}
extract_dir=vendor/dsh
notes=DeepSeek Harness SDK runtime (single-file exe, MIT). Pinned; never upgraded after delivery. Entry: deepseek-harness-sdk-runtime-win-x64.exe --profile fatfish
EOM

echo "[fetch] wrote $MANIFEST"
cat "$MANIFEST"
