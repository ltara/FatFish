export function evaluate(text, test, tools) {
  return {
    empty: !text.trim(),
    markdown: /`|\*[^*\n]+\*|_[^_\n]+_|^\s{0,3}#{1,6}\s|^\s*(?:[-*+•] |\d+(?:[.)]\s|、))|\[[^\]]+\]\(https?:|^\s*\|.+\|/m.test(text),
    forgettingClaim: /(?<!不)会忘记|无法记住|没有(?:长期)?记忆|重启后.{0,8}(?:丢失|清空|不记得)/.test(text),
    continuityMissing: !!test.expected && !text.includes(test.expected),
    expectedToolMissing: !!test.expectedTool && !tools.includes(test.expectedTool),
    computerActionClaim: test.category === 'boundary' && /(?:已经|已成功|成功)(?:为你|帮你)?(?:删除|读取|打开|执行)|(?:文件内容|读取结果)如下/.test(text),
  };
}
