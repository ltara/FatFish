// 生成本地渲染资源，不启动客户端、后台或模型。首帧始终保留激活锁。
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createServer, build } from "vite";
import { renderToString } from "react-dom/server";
import { createElement } from "react";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const configFile = path.join(root, "vite.config.mjs");
const assets = path.join(root, "renderer/assets");
if (!assets.startsWith(root + path.sep) || path.basename(assets) !== "assets") throw Error("ui_asset_path_invalid");
// SSR 与客户端资源必须使用同一 JSX 模式，不能把开发 JSX 转换混入生产运行时。
process.env.NODE_ENV = "production";
const server = await createServer({ configFile, server: { middlewareMode: true }, appType: "custom" });
let markup;
try {
  const { App } = await server.ssrLoadModule("/renderer-src/App.tsx");
  markup = renderToString(createElement(App));
} finally { await server.close(); }
await build({ configFile });
const controllers = ["status-view", "activation-view", "chat-render", "memory-view", "model-view", "onboarding-view", "data-clear-view", "persona-actions", "renderer"];
const scripts = controllers.map(name => `<script type="application/x-fatfish-controller" data-controller src="${name}.js"></script>`).join("\n");
const html = `<!DOCTYPE html>
<!-- Generated by scripts/build-ui.mjs from renderer-src/App.tsx. Do not edit by hand. -->
<html lang="zh-CN"><head><meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self';" />
<title>肥鱼</title><link rel="stylesheet" href="assets/ui.min.css" /><link rel="stylesheet" href="styles.css" />
</head><body class="activation-locked"><div id="ui-root">${markup}</div>
${scripts}
<script defer src="assets/ui.min.js"></script></body></html>\n`;
await fs.writeFile(path.join(root, "renderer/index.html"), html);
await fs.copyFile(path.join(root, "renderer-src/components/ui/SHADCN_LICENSE.txt"), path.join(root, "renderer/SHADCN_LICENSE.txt"));
const notices = ["FatFish UI third-party notices.\n"];
for (const name of ["react", "react-dom", "scheduler", "@radix-ui/react-slot", "@radix-ui/react-compose-refs", "class-variance-authority", "clsx", "tailwind-merge", "tailwindcss"]) {
  const directory = path.join(root, "node_modules", name);
  const metadata = JSON.parse(await fs.readFile(path.join(directory, "package.json"), "utf8"));
  const files = (await fs.readdir(directory)).filter(name => /^(?:license(?:\.[a-z]+)?|notice(?:\.[a-z]+)?)$/i.test(name)).sort();
  if (!files.length) throw Error("ui_dependency_license_missing");
  notices.push(`\n--- ${name} ${metadata.version} (${metadata.license}) ---\n`);
  for (const file of files) notices.push(await fs.readFile(path.join(directory, file), "utf8"));
}
await fs.writeFile(path.join(root, "renderer/THIRD_PARTY_NOTICES.txt"), notices.join("\n"));
console.log("ui_assets_ready: React + shadcn/ui, local-only, activation-locked first frame");
