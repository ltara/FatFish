#!/usr/bin/env bash
# Download Windows vendor assets into vendor/ and write MANIFEST.txt
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/vendor"
NAPCAT_DIR="$VENDOR/napcat"
NODE_DIR="$VENDOR/node"
MANIFEST="$VENDOR/MANIFEST.txt"

NAPCAT_VERSION="${NAPCAT_VERSION:-v4.18.41}"
NAPCAT_ASSET="NapCat.Shell.zip"
NAPCAT_URL="https://github.com/NapNeko/NapCatQQ/releases/download/${NAPCAT_VERSION}/${NAPCAT_ASSET}"

NODE_VERSION="${NODE_VERSION:-v20.20.2}"
NODE_ASSET="node-${NODE_VERSION}-win-x64.zip"
NODE_URL="https://nodejs.org/dist/${NODE_VERSION}/${NODE_ASSET}"

mkdir -p "$NAPCAT_DIR" "$NODE_DIR"
TS="$(date '+%Y-%m-%dT%H:%M:%S%z')"

sha256_file() {
  if command -v sha256sum >/dev/null; then sha256sum "$1" | awk '{print $1}'
  elif command -v shasum >/dev/null; then shasum -a 256 "$1" | awk '{print $1}'
  else openssl dgst -sha256 "$1" | awk '{print $NF}'; fi
}

download() {
  local url="$1" out="$2"
  echo "[fetch] $url"
  curl -fsSL --retry 3 -o "$out" "$url"
}

# --- NapCat Shell (needs user-installed QQ) ---
NAPCAT_ZIP="$VENDOR/$NAPCAT_ASSET"
if [[ ! -f "$NAPCAT_ZIP" ]]; then
  download "$NAPCAT_URL" "$NAPCAT_ZIP"
else
  echo "[fetch] reuse $NAPCAT_ZIP"
fi
NAPCAT_SHA="$(sha256_file "$NAPCAT_ZIP")"
rm -rf "${NAPCAT_DIR:?}/"*
unzip -q -o "$NAPCAT_ZIP" -d "$NAPCAT_DIR"
echo "[fetch] napcat extracted → $NAPCAT_DIR (sha256=$NAPCAT_SHA)"
# Win cmd 秒退若 .bat 为 LF；解压后强制 CRLF（Linux 打包链路必做）
bash "$ROOT/scripts/ensure-crlf.sh" "$NAPCAT_DIR"

# --- Portable Node Win x64 ---
NODE_ZIP="$VENDOR/$NODE_ASSET"
if [[ ! -f "$NODE_ZIP" ]]; then
  download "$NODE_URL" "$NODE_ZIP"
else
  echo "[fetch] reuse $NODE_ZIP"
fi
NODE_SHA="$(sha256_file "$NODE_ZIP")"
TMP_NODE="$(mktemp -d)"
unzip -q -o "$NODE_ZIP" -d "$TMP_NODE"
# zip contains node-vX.Y.Z-win-x64/
INNER="$(find "$TMP_NODE" -maxdepth 1 -type d -name 'node-*' | head -1)"
rm -rf "${NODE_DIR:?}/"*
cp -a "$INNER"/. "$NODE_DIR/"
rm -rf "$TMP_NODE"
echo "[fetch] node extracted → $NODE_DIR (sha256=$NODE_SHA)"

cat > "$MANIFEST" <<EOM
# FatFish vendor manifest — generated by scripts/fetch-vendor
# Do not commit binary blobs under vendor/napcat or vendor/node

[napcat]
version=${NAPCAT_VERSION}
asset=${NAPCAT_ASSET}
url=${NAPCAT_URL}
sha256=${NAPCAT_SHA}
downloaded_at=${TS}
extract_dir=vendor/napcat
notes=Requires user-installed official QQ. Entry: launcher-user.bat / NapCatWinBootMain.exe

[node]
version=${NODE_VERSION}
asset=${NODE_ASSET}
url=${NODE_URL}
sha256=${NODE_SHA}
downloaded_at=${TS}
extract_dir=vendor/node
notes=Portable Node for running bridge + local-server on Windows
EOM

echo "[fetch] wrote $MANIFEST"
cat "$MANIFEST"
