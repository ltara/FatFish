# Download Windows vendor assets into vendor\ and write MANIFEST.txt
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
$Vendor = Join-Path $Root "vendor"
$NapcatDir = Join-Path $Vendor "napcat"
$NodeDir = Join-Path $Vendor "node"
$Manifest = Join-Path $Vendor "MANIFEST.txt"

$NapcatVersion = if ($env:NAPCAT_VERSION) { $env:NAPCAT_VERSION } else { "v4.18.41" }
$NapcatAsset = "NapCat.Shell.zip"
$NapcatUrl = "https://github.com/NapNeko/NapCatQQ/releases/download/$NapcatVersion/$NapcatAsset"

$NodeVersion = if ($env:NODE_VERSION) { $env:NODE_VERSION } else { "v20.20.2" }
$NodeAsset = "node-$NodeVersion-win-x64.zip"
$NodeUrl = "https://nodejs.org/dist/$NodeVersion/$NodeAsset"

New-Item -ItemType Directory -Force -Path $NapcatDir, $NodeDir | Out-Null
$Ts = Get-Date -Format "yyyy-MM-ddTHH:mm:sszzzz"

function Get-Sha256([string]$Path) {
  (Get-FileHash -Algorithm SHA256 -Path $Path).Hash.ToLowerInvariant()
}

function Get-VendorFile([string]$Url, [string]$Out) {
  Write-Host "[fetch] $Url"
  Invoke-WebRequest -Uri $Url -OutFile $Out -UseBasicParsing
}

# --- NapCat ---
$NapcatZip = Join-Path $Vendor $NapcatAsset
if (-not (Test-Path $NapcatZip)) { Get-VendorFile $NapcatUrl $NapcatZip }
else { Write-Host "[fetch] reuse $NapcatZip" }
$NapcatSha = Get-Sha256 $NapcatZip
if (Test-Path $NapcatDir) { Get-ChildItem $NapcatDir | Remove-Item -Recurse -Force }
Expand-Archive -Path $NapcatZip -DestinationPath $NapcatDir -Force
Write-Host "[fetch] napcat → $NapcatDir sha256=$NapcatSha"
# Win cmd dies on LF .bat; normalize after extract
& (Join-Path $PSScriptRoot "ensure-crlf.ps1") $NapcatDir

# --- Node ---
$NodeZip = Join-Path $Vendor $NodeAsset
if (-not (Test-Path $NodeZip)) { Get-VendorFile $NodeUrl $NodeZip }
else { Write-Host "[fetch] reuse $NodeZip" }
$NodeSha = Get-Sha256 $NodeZip
$Tmp = Join-Path $env:TEMP ("fatfish-node-" + [guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Force -Path $Tmp | Out-Null
Expand-Archive -Path $NodeZip -DestinationPath $Tmp -Force
$Inner = Get-ChildItem $Tmp -Directory | Select-Object -First 1
if (Test-Path $NodeDir) { Get-ChildItem $NodeDir | Remove-Item -Recurse -Force }
Copy-Item -Path (Join-Path $Inner.FullName "*") -Destination $NodeDir -Recurse -Force
Remove-Item $Tmp -Recurse -Force
Write-Host "[fetch] node → $NodeDir sha256=$NodeSha"

@"
# FatFish vendor manifest — generated by scripts/fetch-vendor
# Do not commit binary blobs under vendor/napcat or vendor/node

[napcat]
version=$NapcatVersion
asset=$NapcatAsset
url=$NapcatUrl
sha256=$NapcatSha
downloaded_at=$Ts
extract_dir=vendor/napcat
notes=Requires user-installed official QQ. Entry: launcher-user.bat / NapCatWinBootMain.exe

[node]
version=$NodeVersion
asset=$NodeAsset
url=$NodeUrl
sha256=$NodeSha
downloaded_at=$Ts
extract_dir=vendor/node
notes=Portable Node for running bridge + local-server on Windows
"@ | Set-Content -Encoding UTF8 $Manifest

Write-Host "[fetch] wrote $Manifest"
Get-Content $Manifest
